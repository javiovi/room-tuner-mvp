import {expect,test} from "@playwright/test"
import {mockAnalysis} from "../lib/mockData"
test.beforeEach(async({page},testInfo)=>{
 await page.addInitScript(({analysis,music})=>{
  if(!sessionStorage.getItem("roomtuner-session"))sessionStorage.setItem("roomtuner-session",JSON.stringify({version:1,state:{project:{goal:music?"music":"instrument",concern:"clarity",dimensionSource:"measured",widthM:4,lengthM:5,heightM:3,floorType:"madera",wallType:"desnudas",speakerPlacement:"pared-corta-centrado",listeningPosition:"centro-sala",furniture:[]},analysis:{...analysis,roomDiagram:{...analysis.roomDiagram,floorPlan:{...analysis.roomDiagram.floorPlan,furnitureLayout:[]}},generatedAt:"2026-11-10T15:00:00Z"},projectId:null,analysisPersisted:false,reportPersonalization:{}}}))
 },{analysis:mockAnalysis,music:testInfo.title.startsWith("music")})
})
test("instruments use a single source, recording and reinforcement compare opposite distances",async({page})=>{
 const errors:string[]=[];page.on("pageerror",e=>errors.push(e.message))
 await page.goto("/resultado")
 const workspace=page.getByRole("region",{name:"Tu espacio, en vivo"})
 await expect(workspace.getByRole("button",{name:"El plano representa mi habitación"})).toBeDisabled()
 await expect(workspace.locator('[data-live-object^="speaker-"]')).toHaveCount(1)
 await workspace.getByRole("button",{name:"Grabar con micrófono",exact:true}).click()
 await workspace.getByRole("button",{name:"El plano representa mi habitación"}).click()
 await expect(workspace.locator("[data-reflection-site]")).toHaveCount(1)
 await workspace.getByText("Ajustar posiciones y alturas",{exact:true}).click()
 await expect(workspace.getByRole("option",{name:"Micrófono",exact:true})).toHaveCount(1)
 await expect(workspace.getByRole("option",{name:"Parlante R",exact:true})).toHaveCount(0)
 await workspace.getByRole("button",{name:"Probar un cambio pequeño"}).click()
 await expect(workspace.getByText(/La prueba acerca instrumento y micrófono/)).toBeVisible()
 const distance=()=>page.evaluate(()=>{
  const l=JSON.parse(sessionStorage.getItem("roomtuner-session")!).state.reportPersonalization.layout
  const d=(p:typeof l.current)=>Math.hypot((p.speakerPositions[0].x-p.listeningPosition.x)*p.width,(p.speakerPositions[0].y-p.listeningPosition.y)*p.length)
  return {before:d(l.current),after:d(l.proposal)}
 })
 const record=await distance();expect(record.after).toBeLessThan(record.before)
 await workspace.getByRole("button",{name:"Actual",exact:true}).click()
 await workspace.getByRole("button",{name:"Amplificar con micrófono abierto",exact:true}).click()
 await workspace.getByRole("button",{name:"El plano representa mi habitación"}).click()
 await workspace.getByRole("button",{name:"Probar un cambio pequeño"}).click()
 await expect(workspace.getByText(/No predice cuánto volumen admite el sistema/)).toBeVisible()
 const live=await distance();expect(live.after).toBeGreaterThan(live.before)
 await page.reload()
 await expect(workspace.getByRole("button",{name:"Amplificar con micrófono abierto",exact:true})).toHaveAttribute("aria-pressed","true")
 await expect(workspace.getByText("Plano confirmado por vos",{exact:true})).toBeVisible()
 expect(errors).toEqual([])
})
test("music reverberation compares material bands and retains a subjective trial locally",async({page})=>{
 const posts:string[]=[];page.on("request",r=>{if(r.method()==="POST")posts.push(r.url())})
 await page.goto("/resultado")
 const reverb=page.getByRole("region",{name:"Reverberación y confort",exact:true})
 await reverb.getByText("Comparar con un elemento que ya tengo",{exact:true}).click()
 const baseline=await reverb.locator('[data-reverb-value="baseline-mid"]').textContent()
 await reverb.getByLabel("Elemento para comparar",{exact:true}).selectOption("rug")
 const after=await reverb.locator('[data-reverb-value="trial-mid"]').textContent()
 expect(after).not.toBe(baseline)
 await expect(reverb.getByText(/no RT60 medido/)).toBeVisible()
 await reverb.getByRole("button",{name:"Igual",exact:true}).click()
 await expect(reverb.getByText(/No recomendamos sumar absorción/)).toBeVisible()
 await page.reload()
 await reverb.getByText("Comparar con un elemento que ya tengo",{exact:true}).click()
 await expect(reverb.getByLabel("Elemento para comparar",{exact:true})).toHaveValue("rug")
 await expect(reverb.getByRole("button",{name:"Igual",exact:true})).toHaveAttribute("aria-pressed","true")
 await reverb.getByRole("button",{name:"Volver al modelo actual",exact:true}).click()
 await expect(reverb.locator('[data-reverb-value="trial-mid"]')).toHaveText(baseline!)
 expect(posts).toEqual([])
})
