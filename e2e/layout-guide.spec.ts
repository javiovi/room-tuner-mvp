import { expect, test } from "@playwright/test"
import { mockAnalysis } from "../lib/mockData"

const project = { goal: "music", concern: "bass", dimensionSource: "measured", lengthM: 5, widthM: 4, heightM: 3, floorType: "madera", wallType: "desnudas", furniture: ["sofa"], speakerPlacement: "esquina", listeningPosition: "sillon-pared-posterior", moveConstraints: { speakers: true, listening: true, furniture: false } }
test.beforeEach(async ({ page }, testInfo) => {
  await page.addInitScript(({ project, analysis }) => {
    if (!sessionStorage.getItem("roomtuner-session")) sessionStorage.setItem("roomtuner-session", JSON.stringify({ version: 1, state: { project, analysis, projectId: null, analysisPersisted: false, reportPersonalization: {} } }))
  }, { project: { ...project, concern: testInfo.title.startsWith("structural") ? "noise" : testInfo.title.startsWith("unable") ? "clarity" : project.concern, ...(testInfo.title.startsWith("structural") ? { noiseSource: "neighbors", noiseEntry: "wall" } : {}) }, analysis: mockAnalysis })
})

test("live reflection sites follow positions and a small trial preserves the baseline and PDF notes", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror",e=>errors.push(e.message))
  await page.goto("/resultado")
  const workspace=page.getByRole("region",{name:"Tu espacio, en vivo"})
  await expect(workspace).toBeVisible()
  await expect(page.getByRole("article")).toHaveCount(0)
  await expect(workspace.locator("[data-reflection-site]")).toHaveCount(0)
  await expect(workspace.getByRole("button",{name:"Probar un cambio pequeño"})).toBeDisabled()
  await workspace.getByRole("button",{name:"El plano representa mi habitación"}).click()
  await expect(workspace.locator("[data-reflection-site]")).toHaveCount(2)
  const site=workspace.locator('[data-reflection-site="0-left"]')
  const before=await site.getAttribute("data-y")
  await workspace.getByText("Ajustar posiciones y alturas",{exact:true}).click()
  await workspace.getByLabel("Objeto a mover").selectOption("speaker-0")
  await workspace.getByRole("button",{name:"Mover a la derecha",exact:true}).click()
  await expect.poll(()=>site.getAttribute("data-y")).not.toBe(before)
  const baseline=await workspace.locator('[data-live-object="speaker-0"]').getAttribute("data-x")
  await workspace.getByRole("button",{name:"Probar un cambio pequeño"}).click()
  await expect(workspace.getByText("Movimiento propuesto",{exact:true})).toBeVisible()
  const state=await page.evaluate(()=>JSON.parse(sessionStorage.getItem("roomtuner-session")!).state.reportPersonalization.layout)
  expect(state.current.speakerPositions[0].x).toBe(Number(baseline))
  const movements=[...state.current.speakerPositions,state.current.listeningPosition].map((p:{x:number;y:number},i:number)=>{const q=[...state.proposal.speakerPositions,state.proposal.listeningPosition][i];return Math.hypot((p.x-q.x)*state.current.width,(p.y-q.y)*state.current.length)})
  expect(Math.max(...movements)).toBeLessThanOrEqual(.300001)
  await workspace.getByRole("button",{name:"Actual",exact:true}).click()
  await expect(workspace.locator('[data-live-object="speaker-0"]')).toHaveAttribute("data-x",baseline!)
  await workspace.getByRole("button",{name:"Mostrar dónde probar un absorbente"}).click()
  await expect(workspace.locator("[data-treatment-site]")).toHaveCount(2)
  await workspace.getByRole("button",{name:"Igual",exact:true}).click()
  await expect(workspace.getByText(/No recomendamos comprar un absorbente/)).toBeVisible()
  await workspace.getByRole("button",{name:"Mejoró",exact:true}).click()
  await expect(workspace.getByText(/panel independiente para esta zona/)).toBeVisible()
  await page.getByText("Registrar la prueba y ver otras opciones",{exact:true}).click()
  await page.getByLabel("Mejoró",{exact:true}).check()
  await page.getByLabel("¿Qué cambiaste? (opcional)").fill("Otro asiento")
  await page.reload()
  await expect(workspace.getByText("Plano confirmado por vos",{exact:true})).toBeVisible()
  await page.getByText("Registrar la prueba y ver otras opciones",{exact:true}).click()
  await expect(page.getByLabel("Mejoró",{exact:true})).toBeChecked()
  await expect(page.getByLabel("¿Qué cambiaste? (opcional)")).toHaveValue("Otro asiento")
  let payload: {personalization:{experiments:{position:unknown}}}|undefined
  await page.route("**/api/generate-pdf",async route=>{payload=route.request().postDataJSON();await route.fulfill({contentType:"application/pdf",body:"%PDF-1.4\n"})})
  await page.getByRole("button",{name:/Descargar PDF/i}).click()
  await expect.poll(()=>payload?.personalization.experiments.position).toEqual({tried:true,outcome:"better",note:"Otro asiento"})
  expect(errors).toEqual([])
})

test("unable is not counted as tried and another option retains the earlier note", async ({ page }) => {
  await page.goto("/resultado")
  await page.getByText("Registrar la prueba y ver otras opciones",{exact:true}).click()
  await page.getByLabel("No pude probarlo",{exact:true}).check()
  await page.getByLabel("¿Qué cambiaste? (opcional)").fill("No puedo mover el asiento hoy")
  await page.getByRole("button",{name:"Probar otra alternativa"}).click()
  await expect(page.getByRole("article")).toHaveCount(1)
  await expect(page.getByRole("heading",{name:"Compará dos lugares de escucha"})).toBeVisible()
  await page.reload()
  await page.getByText("Registrar la prueba y ver otras opciones",{exact:true}).click()
  await expect(page.getByRole("heading",{name:"Compará dos lugares de escucha"})).toBeVisible()
  await page.getByRole("button",{name:"Volver a la prueba anterior"}).click()
  await expect(page.getByLabel("No pude probarlo",{exact:true})).toBeChecked()
  await expect(page.getByLabel("¿Qué cambiaste? (opcional)")).toHaveValue("No puedo mover el asiento hoy")
  const record = await page.evaluate(()=>JSON.parse(sessionStorage.getItem("roomtuner-session")!).state.reportPersonalization.experiments.symmetry)
  expect(record.tried).toBe(false)
})

test("technical estimates do not prescribe treatment and English stays usable", async ({ page }) => {
  await page.goto("/resultado")
  await page.getByRole("tab",{name:"Quiero entender más"}).click()
  await page.locator("summary").filter({hasText:/^Modos de sala$/}).click()
  await expect(page.getByText(/no indican cuánto se escuchan/i)).toBeVisible()
  await expect(page.getByText(/requieren tratamiento|Modos críticos|Alta severidad/i)).toHaveCount(0)
  await page.getByRole("button",{name:"Cambiar a inglés"}).click()
  await page.getByRole("tab",{name:"What to try today"}).click()
  await expect(page.getByRole("heading",{name:"Your space, live"})).toBeVisible()
  await page.getByText("Record a trial and see other options",{exact:true}).click()
  await expect(page.getByRole("heading",{name:"Compare two listening positions"})).toBeVisible()
  await expect(page.getByLabel("I could not try it",{exact:true})).toBeVisible()
})


