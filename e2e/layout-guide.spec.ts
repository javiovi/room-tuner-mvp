import { expect, test } from "@playwright/test"
import { mockAnalysis } from "../lib/mockData"

test("guided preview moves only the listening spot, preserves the layout and shares results with the PDF", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", e => errors.push(e.message))
  const project = { goal: "music", concern: "bass", dimensionSource: "measured", lengthM: 5, widthM: 4, heightM: 3, floorType: "madera", wallType: "desnudas", furniture: ["sofa", "estanteria"], speakerPlacement: "esquina", listeningPosition: "sillon-pared-posterior", moveConstraints: { speakers: false, listening: true, furniture: false } }
  await page.addInitScript(({ project, analysis }) => {
    if (!sessionStorage.getItem("roomtuner-session")) sessionStorage.setItem("roomtuner-session", JSON.stringify({ version: 1, state: { project, analysis, projectId: null, analysisPersisted: false, reportPersonalization: {} } }))
  }, { project, analysis: mockAnalysis })
  await page.goto("/resultado")
  const planner = page.getByRole("region", { name: "Probá otra distribución" })
  await expect(planner.getByRole("heading", { name: "Compará dos lugares de escucha" })).toBeVisible()
  const speaker = planner.locator('[data-object="speaker-0"]')
  const listener = planner.locator('[data-object="listening"]')
  const speakerX = await speaker.getAttribute("data-x")
  const listenerY = await listener.getAttribute("data-y")
  await planner.getByRole("button", { name: "Mostrame cómo" }).click()
  await expect(planner.getByText("Vista previa de la prueba", { exact: true })).toBeVisible()
  await expect.poll(() => listener.getAttribute("data-y")).not.toBe(listenerY)
  await expect(speaker).toHaveAttribute("data-x", speakerX!)
  // A preview must not silently replace either saved arrangement.
  const snapshot = await page.evaluate(() => JSON.parse(sessionStorage.getItem("roomtuner-session")!).state.reportPersonalization.layout)
  expect(snapshot.view).toBe("current")
  expect(snapshot.current.listeningPosition.y).toBe(Number(listenerY))
  await expect.poll(() => listener.evaluate(el => el.getAnimations().length)).toBe(0)
  await planner.screenshot({ path: "/tmp/roomtuner-guided-preview-mobile.png" })
  await planner.getByRole("button", { name: "Volver al plano" }).click()
  await expect(listener).toHaveAttribute("data-y", listenerY!)
  await planner.getByRole("button", { name: "Ya lo probé" }).click()
  await planner.getByLabel("Mejoró", { exact: true }).check()
  await expect(planner.getByText(/Conservá el cambio/)).toBeVisible()
  const firstAction = page.getByRole("article").first()
  await expect(firstAction.getByLabel("Lo probé", { exact: true })).toBeChecked()
  await expect(firstAction.getByLabel("Mejoró", { exact: true })).toBeChecked()
  await firstAction.getByLabel("¿Qué cambiaste? (opcional)").fill("Escuché desde otro asiento")
  await page.reload()
  await expect(planner.getByLabel("Mejoró", { exact: true })).toBeChecked()
  await expect(firstAction.getByLabel("¿Qué cambiaste? (opcional)")).toHaveValue("Escuché desde otro asiento")
  let payload: { personalization: { experiments: { position: { tried: boolean; outcome: string; note: string } } } } | undefined
  await page.route("**/api/generate-pdf", async route => {
    payload = route.request().postDataJSON()
    await route.fulfill({ contentType: "application/pdf", body: "%PDF-1.4\n" })
  })
  await page.getByRole("button", { name: /Descargar PDF/i }).click()
  await expect.poll(() => payload?.personalization.experiments.position).toEqual({ tried: true, outcome: "better", note: "Escuché desde otro asiento" })
  await page.emulateMedia({ reducedMotion: "reduce", colorScheme: "dark" })
  await planner.getByRole("button", { name: "Mostrame cómo" }).click()
  await expect.poll(() => listener.getAttribute("data-y")).not.toBe(listenerY)
  expect(await listener.evaluate(el => getComputedStyle(el).transitionDuration)).toBe("0s")
  await expect(page.locator("html")).toHaveClass(/dark/)
  await planner.screenshot({ path: "/tmp/roomtuner-guided-preview-dark.png" })
  expect(errors).toEqual([])
})

test("noise guidance stays in place and is translated on desktop", async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 960 })
  await page.addInitScript(analysis => {
    localStorage.setItem("roomtuner-locale", "en")
    const project = { goal: "work", concern: "noise", dimensionSource: "approximate", lengthM: 5, widthM: 4, heightM: 2.5, furniture: ["sofa"], moveConstraints: { speakers: false, listening: false, furniture: false } }
    sessionStorage.setItem("roomtuner-session", JSON.stringify({ version: 1, state: { project, analysis, projectId: null, analysisPersisted: false, reportPersonalization: {} } }))
  }, mockAnalysis)
  await page.goto("/resultado")
  const planner = page.getByRole("region", { name: "Try another layout" })
  const listener = planner.locator('[data-object="listening"]')
  const before = await listener.getAttribute("data-y")
  await planner.getByRole("button", { name: "Show me how" }).click()
  await expect(planner.getByText("Pause a noise source and listen again", { exact: true })).toBeVisible()
  await expect(listener).toHaveAttribute("data-y", before!)
  await expect(planner.getByRole("heading", { name: "Identify a source of noise" })).toBeVisible()
  await expect(planner.getByRole("img")).toHaveAccessibleName("Try another layout: Experiment preview")
  const comparison = planner.getByRole("region", { name: "What changes between Current and Proposal" })
  await expect(comparison.getByText("Visual comparison of the approximate sketch. Add measurements to see distances in metres.")).toBeVisible()
  await expect(comparison.locator("[data-case]")).toHaveCount(0)
  await planner.screenshot({ path: "/tmp/roomtuner-guided-preview-desktop-en.png" })
})

test("geometry comparison updates both arrangements, survives reload and leaves acoustic results unchanged", async ({ page }) => {
  const analysis = { ...mockAnalysis, roomDiagram: { ...mockAnalysis.roomDiagram, floorPlan: { ...mockAnalysis.roomDiagram.floorPlan, width: 4, length: 6, furnitureLayout: [] } } }
  const project = { goal: "music", concern: "bass", dimensionSource: "measured", lengthM: 6, widthM: 4, heightM: 3, furniture: [], speakerPlacement: "pared-corta-centrado", listeningPosition: "sillon-pared-posterior", moveConstraints: { speakers: false, listening: true, furniture: false } }
  await page.addInitScript(({ project, analysis }) => {
    if (!sessionStorage.getItem("roomtuner-session")) sessionStorage.setItem("roomtuner-session", JSON.stringify({ version: 1, state: { project, analysis, projectId: null, analysisPersisted: false, reportPersonalization: {} } }))
  }, { project, analysis })
  await page.goto("/resultado")
  const planner = page.getByRole("region", { name: "Probá otra distribución" })
  const comparison = planner.getByRole("region", { name: "Qué cambia entre Actual y Propuesta" })
  const currentDistance = comparison.locator('[data-geometry="left"] [data-case="current"]')
  const proposalDistance = comparison.locator('[data-geometry="left"] [data-case="proposal"]')
  await expect(currentDistance).toHaveText("4,45 m")
  await expect(proposalDistance).toHaveText("1,75 m")
  await planner.getByLabel("Mostrar distancias en el plano").check()
  await expect(planner.locator("[data-distance-triangle]")).toHaveCount(1)
  await planner.getByText("Acomodar el plano y las restricciones", { exact: true }).click()
  await planner.getByLabel("Elegí un objeto").selectOption("listening")
  await planner.getByRole("button", { name: "Mover a la derecha", exact: true }).click()
  await expect(currentDistance).toHaveText("4,49 m")
  await expect(proposalDistance).toHaveText("1,75 m")
  await comparison.getByText("Distancia a paredes y movimientos", { exact: true }).click()
  await expect(comparison.locator('[data-wall-object="2"] [data-case="current"]')).toContainText("0,90 m")
  await expect(comparison.locator('[data-movement="speaker-0"]')).toContainText("Sin cambio")
  await comparison.screenshot({ path: "/tmp/roomtuner-geometry-mobile.png" })
  await page.reload()
  await expect(currentDistance).toHaveText("4,49 m")
  await expect(proposalDistance).toHaveText("1,75 m")
  const storedAnalysis = await page.evaluate(() => JSON.parse(sessionStorage.getItem("roomtuner-session")!).state.analysis)
  expect(storedAnalysis.roomMetrics).toEqual(analysis.roomMetrics)
  expect(storedAnalysis.frequencyResponse).toEqual(analysis.frequencyResponse)
  await page.emulateMedia({ colorScheme: "dark" })
  await expect(page.locator("html")).toHaveClass(/dark/)
  await comparison.screenshot({ path: "/tmp/roomtuner-geometry-dark.png" })
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole("button", { name: "Cambiar a inglés", exact: true }).click()
  const englishComparison = page.getByRole("region", { name: "What changes between Current and Proposal" })
  await expect(englishComparison.getByRole("heading", { name: "What changes between Current and Proposal" })).toBeVisible()
  await expect(englishComparison.locator('[data-geometry="left"] [data-case="current"]')).toHaveText("4.49 m")
  await englishComparison.screenshot({ path: "/tmp/roomtuner-geometry-desktop-en.png" })
})
